"""Generate a Pykwalify schema for every reference HFP and validate HFPs against them.

Each reference HFP `<comp>/current/**/hfp-<name>.yaml` gets a sibling
`hfp-<name>-schema.yaml`, generated from two sources:

  The reference HFP
    Its structure: every key, the type of every value, which keys every
    entry of a list carries. A key in the reference HFP is required; a key
    only some list entries carry is optional.

  The module's AIDL
    The values a string may take. A string list or key whose reference
    values all belong to one AIDL enum accepts every value of that enum,
    so a product HFP may list a value the reference HFP does not.

  Keys that name something rather than a field are matched by pattern:
  resource ids (`- 0:`), and the single, capitalised key of a list entry
  (`- H264_AVC:`, `- Entertainment:`), which is held to its AIDL enum when
  it has one.

Usage
  hfp_schema.py generate            write every schema beside its HFP
  hfp_schema.py check               fail if a committed schema is out of date
  hfp_schema.py validate [HFP ...]  validate the reference HFPs, or the
                                    given product HFPs, against their schema
      --schema FILE                 validate against FILE instead
      --release VERSION             use the schema frozen in <comp>/VERSION/

Needs ruamel.yaml (generate, check) and pykwalify (validate); run through
scripts/validate_hfp.sh, which provides both.
"""

