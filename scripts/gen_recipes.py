"""Generate the meta-rdk-halif BitBake recipes - one recipe per HAL component.

Each component is emitted as
  tests/yocto/meta-rdk-halif/recipes-halif/rdk-halif-<comp>/rdk-halif-<comp>.bb

The component version is not baked into the recipe: HALIF_VERSION defaults to the
latest released snapshot and a build configuration selects a different version
per component with `HALIF_VERSION:pn-rdk-halif-<comp>` (generated from a versions
manifest by scripts/gen_team_conf.py). Because a component's sibling
dependencies differ by version, the recipe carries a version->siblings map so
DEPENDS follows whichever HALIF_VERSION is selected.

Dependency versions come from each snapshot's CMakeLists.txt link names
(`<dep>-v<X.Y.Z.W>-cpp`). release.sh writes those fully resolved - interface.yaml
`imports:` may carry `@current`, which release.sh pins there at freeze time - so
the link names are the ground truth of what the committed C++ links.

Usage:
  scripts/gen_recipes.py            # regenerate recipes
  scripts/gen_recipes.py --check    # verify recipes are up to date (no writes)
"""
import os
import re
import shutil
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAYER = os.path.join(REPO_ROOT, "tests", "yocto", "meta-rdk-halif")
RECIPES_DIR = os.path.join(LAYER, "recipes-halif")

VER_RE = re.compile(r"^\d+\.\d+\.\d+\.\d+$")
LINK_RE = re.compile(r"([a-z0-9]+)-v(\d+\.\d+\.\d+\.\d+)-cpp")


def version_tuple(ver):
    return tuple(int(p) for p in ver.split("."))


def parse_deps(comp, ver):
    """Return sorted [(dep_comp, dep_ver), ...] the snapshot links, from its CMakeLists."""
    cml = os.path.join(REPO_ROOT, comp, ver, "CMakeLists.txt")
    deps = set()
    with open(cml) as fh:
        text = fh.read()
    for block in re.findall(r"target_link_libraries\(([^)]*)\)", text):
        for dep, dver in LINK_RE.findall(block):
            if dep != comp:
                deps.add((dep, dver))
    return sorted(deps)


def discover_all():
    """Map component -> sorted list of released versions."""
    found = {}
    for comp in sorted(os.listdir(REPO_ROOT)):
        comp_dir = os.path.join(REPO_ROOT, comp)
        if not os.path.isdir(comp_dir) or comp.startswith("."):
            continue
        vers = [
            v for v in os.listdir(comp_dir)
            if VER_RE.match(v) and os.path.isfile(os.path.join(comp_dir, v, "CMakeLists.txt"))
        ]
        if vers:
            found[comp] = sorted(vers, key=version_tuple)
    return found


HEADER = """# Auto-generated by scripts/gen_recipes.py - do not hand-edit.
# One recipe per component; a build configuration selects the version per
# component with HALIF_VERSION:pn-rdk-halif-{comp} (see scripts/gen_team_conf.py).
"""


def recipe_text(comp, versions):
    latest = versions[-1]
    lines = [HEADER.format(comp=comp)]
    lines.append('SUMMARY = "RDK HAL AIDL interface library: %s"' % comp)
    lines.append('')
    lines.append('HALIF_MODULE = "%s"' % comp)
    lines.append('# Released versions: %s. Default is the latest.' % ", ".join(versions))
    lines.append('HALIF_VERSION ??= "%s"' % latest)

    # Per-version sibling dependencies (component names; the selected
    # HALIF_VERSION picks the row). Omitted for a component that never links a
    # sibling at any version.
    ver_deps = {v: parse_deps(comp, v) for v in versions}
    if any(ver_deps.values()):
        mapping = ", ".join(
            "'%s': '%s'" % (v, " ".join("rdk-halif-%s" % d for d, _ in ver_deps[v]))
            for v in versions
        )
        lines.append('# Sibling deps by version (resolved from each snapshot).')
        lines.append(
            'HALIF_SIBLINGS = "${@ {%s}.get(d.getVar(\'HALIF_VERSION\'), \'\') }"' % mapping
        )
    lines.append('')
    lines.append('inherit rdk-halif-module')
    return "\n".join(lines) + "\n"


def check_consistency(found):
    """Return errors if the latest cohort (the zero-config default) is inconsistent."""
    errors = []
    latest = {c: v[-1] for c, v in found.items()}
    for comp, versions in found.items():
        cml = os.path.join(REPO_ROOT, comp, latest[comp], "CMakeLists.txt")
        with open(cml) as fh:
            text = fh.read()
        for block in re.findall(r"target_link_libraries\(([^)]*)\)", text):
            for dep, dver in LINK_RE.findall(block):
                if dep == comp:
                    continue
                if dep not in found:
                    errors.append("latest %s links unknown component %s" % (comp, dep))
                elif dver != latest[dep]:
                    errors.append(
                        "latest %s@%s links %s@%s but latest %s is %s "
                        "(zero-config default cohort would be inconsistent)"
                        % (comp, latest[comp], dep, dver, dep, latest[dep])
                    )
    return errors


def main():
    check = "--check" in sys.argv[1:]
    found = discover_all()

    errors = check_consistency(found)
    if errors:
        sys.stderr.write("gen_recipes: consistency errors:\n")
        for e in errors:
            sys.stderr.write("  - %s\n" % e)
        return 2

    want = {}
    for comp, versions in found.items():
        out = os.path.join(RECIPES_DIR, "rdk-halif-%s" % comp, "rdk-halif-%s.bb" % comp)
        want[out] = recipe_text(comp, versions)

    # Detect stale recipe files (e.g. an old per-version layout) to remove.
    have = set()
    if os.path.isdir(RECIPES_DIR):
        for root, _dirs, files in os.walk(RECIPES_DIR):
            for f in files:
                if f.endswith(".bb"):
                    have.add(os.path.join(root, f))
    stale = sorted(have - set(want))

    def current(path):
        if not os.path.isfile(path):
            return None
        with open(path) as fh:
            return fh.read()

    changed = [o for o, t in want.items() if current(o) != t]

    if check:
        problems = [os.path.relpath(p, REPO_ROOT) for p in stale + changed]
        if problems:
            sys.stderr.write("gen_recipes: recipes out of date (run ./scripts/gen_recipes.py):\n")
            for p in sorted(problems):
                sys.stderr.write("  - %s\n" % p)
            return 1
        print("gen_recipes: %d component recipes up to date." % len(want))
        return 0

    for p in stale:
        os.remove(p)
        print("  removed %s" % os.path.relpath(p, REPO_ROOT))
    # Drop any now-empty per-version recipe directories left behind.
    for comp in found:
        d = os.path.join(RECIPES_DIR, "rdk-halif-%s" % comp)
        if os.path.isdir(d) and not os.listdir(d):
            shutil.rmtree(d)
    for out in sorted(changed):
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w") as fh:
            fh.write(want[out])
        print("  wrote %s" % os.path.relpath(out, REPO_ROOT))

    print("gen_recipes: generated %d component recipes (%d written, %d stale removed)."
          % (len(want), len(changed), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
